class StructuredData(unittest.TestCase):
    def test_every_block_parses_and_every_reference_resolves(self):
        for fname in (PROFILE, BAYANATH):
            g = graph(read(fname))
            ids, refs = set(), []

            def walk(o):
                if isinstance(o, dict):
                    if '@id' in o and len(o) > 1:
                        ids.add(o['@id'])
                    elif set(o) == {'@id'}:
                        refs.append(o['@id'])
                    for v in o.values():
                        walk(v)
                elif isinstance(o, list):
                    for v in o:
                        walk(v)
            walk(g)
            for r in refs:
                self.assertIn(r, ids, f'{fname}: {r} is referenced but not defined')

    def test_the_person_is_the_same_entity_on_both_pages(self):
        pa = [n for n in graph(read(PROFILE)) if n.get('@type') == 'Person'][0]
        pb = [n for n in graph(read(BAYANATH)) if n.get('@type') == 'Person'][0]
        self.assertEqual(pa, pb)
        self.assertEqual(pa['name'], NAME)
        self.assertEqual(pa['jobTitle'], APPROVED_ROLES)
        self.assertNotIn('alternateName', pa)
        self.assertIn('https://www.youtube.com/@MuftiMaqsoodImran', pa['sameAs'])
        self.assertIn('https://linktr.ee/MuftiMaqsoodImran', pa['sameAs'])
        self.assertTrue(pa.get('affiliation') or pa.get('worksFor'))

    def test_types(self):
        self.assertLessEqual({'ProfilePage', 'Person', 'Organization', 'BreadcrumbList'}, types_of(graph(read(PROFILE))))
        gb = graph(read(BAYANATH))
        self.assertLessEqual({'CollectionPage', 'ItemList', 'Person', 'Organization'}, types_of(gb))
        videos = [i['item'] for n in gb if n['@type'] == 'ItemList' for i in n['itemListElement']]
        self.assertTrue(videos)
        for v in videos:
            self.assertEqual(v['@type'], 'VideoObject')
            self.assertTrue(v['uploadDate'] and v['thumbnailUrl'] and v['name'])

    def test_video_objects_describe_exactly_the_cards_on_the_page(self):
        page = read(BAYANATH)
        cards = re.findall(r'class="by-title" href="https://www\.youtube\.com/watch\?v=([\w-]{11})"', page)
        in_data = [i['item']['url'].split('=')[1] for n in graph(page) if n['@type'] == 'ItemList' for i in n['itemListElement']]
        self.assertTrue(set(in_data) <= set(cards))


