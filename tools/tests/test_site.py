        vids = [{'id': 'AAAAAAAAAAA', 'title': 'x'}, {'id': 'BBBBBBBBBBB', 'title': 'y'}, {'id': 'CCCCCCCCCCC', 'title': 'z'}]
        ov = {'BBBBBBBBBBB': 'Another Speaker', 'CCCCCCCCCCC': False}
        self.assertEqual(R.speaker_of(vids[1], ov, NAME), ('Another Speaker', False))
        self.assertEqual(R.speaker_of(vids[2], ov, NAME), (None, False))
        self.assertEqual(R.speaker_of(vids[0], ov, NAME)[0], NAME)

