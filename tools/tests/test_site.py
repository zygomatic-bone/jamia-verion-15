class Wording(unittest.TestCase):
    def source_files(self):
        for p in ROOT.rglob('*'):
            rel = p.relative_to(ROOT).parts
            if p.is_file() and not {'.git', '__pycache__', 'node_modules'} & set(rel) and p.suffix.lower() in {
                    '.html', '.css', '.js', '.mjs', '.json', '.md', '.py', '.yml', '.yaml', '.toml', '.txt', '.xml', '', '.gitattributes'}:
                yield p

    def test_no_unwanted_scholar_wording_anywhere(self):
        for p in self.source_files():
            if p.name == 'test_site.py':
                continue
            text = p.read_text(encoding='utf-8', errors='ignore')
            for u in UNWANTED:
                if u == 'not verified' and p.suffix in ('.py', '.js'):
                    continue   # a condition in code, not wording
                self.assertNotIn(u, text, f'{p.relative_to(ROOT)}: {u}')

    def test_nothing_describes_how_the_site_was_produced(self):
        for p in self.source_files():
            if p.name == 'test_site.py':
                continue
            text = p.read_text(encoding='utf-8', errors='ignore')
            m = PRODUCTION_WORDS.search(text)
            self.assertIsNone(m, f'{p.relative_to(ROOT)}: {m and m.group(0)}')

    def test_nothing_refers_to_the_removed_generator_files(self):
        gone = re.compile(r'build\.py|generate_\w+\.py|portal-ui/|tools/connect|tools/speaker|tools/support|tools/masjid|AGENTS\.md|schema\.generated')
        for p in self.source_files():
            if p.name == 'test_site.py':
                continue
            m = gone.search(p.read_text(encoding='utf-8', errors='ignore'))
            self.assertIsNone(m, f'{p.relative_to(ROOT)}: {m and m.group(0)}')


