def read(name):
    return (PUB / name).read_text(encoding='utf-8')


def public_pages():
    return sorted(PUB.rglob('*.html'))


def url_for(rel):
    if rel.endswith('index.html'):
        return f'{ORIGIN}/{rel[:-len("index.html")]}'
    return f'{ORIGIN}/{rel}'


def visible(html):
    """The page without data blocks and scripts, tags removed, spacing collapsed."""
    html = re.sub(r'<script.*?</script>|<style.*?</style>', ' ', html, flags=re.S)
    return unescape(re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', html)))


def tight(html):
    """Markup with the indentation between tags removed, so that patterns need not know the layout."""
    return re.sub(r'>\s+<', '><', html)


def graph(html):
    out = []
    for m in LD.finditer(html):
        out += json.loads(m.group(1))['@graph']
    return out


def types_of(g):
    return {t for n in g for t in (n['@type'] if isinstance(n['@type'], list) else [n['@type']])}


