"""Writes serverless/forms-worker/src/schema.generated.js from tools/connect/forms-schema.json.

The same JSON file builds the HTML forms (tools/connect/connect_pages.py) and is what the Worker validates against, so a page and the
service cannot drift apart. Run through  python tools/build.py  (or alone: python tools/generate_forms_worker.py). Never edit the output by hand.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / 'tools' / 'connect' / 'forms-schema.json'
OUT = ROOT / 'serverless' / 'forms-worker' / 'src' / 'schema.generated.js'


def render():
    schema = json.loads(SCHEMA.read_text(encoding='utf-8'))
    schema.pop('_note', None)
    data = json.dumps(schema, ensure_ascii=True, indent=2)
    return ('/* GENERATED by tools/generate_forms_worker.py from tools/connect/forms-schema.json. Do not edit by hand. */\n'
            f'export default {data};\n')


if __name__ == '__main__':
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding='utf-8', newline='\n')
    print(f'wrote {OUT.relative_to(ROOT)}')
